export type IconName = keyof typeof LUCIDE | keyof typeof MEANS;

const markup = (name: IconName): string =>
  name in MEANS ? LUCIDE[MEANS[name as keyof typeof MEANS]] : LUCIDE[name as keyof typeof LUCIDE];

/**
 * An icon: 16px in a row or a button, 20 in a header or the sidebar, 24 on the phone's tab bar.
 * It's hidden from screen readers, since the text beside it (or the button's name) says what it
 * is; `label` is for one that stands alone, such as a tick after a name.
 */
export function Icon(props: {
  name: IconName;
  size?: number;
  class?: string;
  /** Filled with its colour as well as drawn: a set star. */
  filled?: boolean;
  label?: string;
}) {
  return (
    <>
      <svg
        xmlns="http://www.w3.org/2000/svg"
        viewBox="0 0 24 24"
        width={props.size ?? 16}
        height={props.size ?? 16}
        fill={props.filled ? "currentColor" : "none"}
        stroke="currentColor"
        stroke-width="1.75"
        stroke-linecap="round"
        stroke-linejoin="round"
        class={`shrink-0 ${props.class ?? ""}`}
        aria-hidden="true"
        innerHTML={markup(props.name)}
      />
      <Show when={props.label}>
        <span class="sr-only"> {props.label}</span>
      </Show>
    </>
  );
}
